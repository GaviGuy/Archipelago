import json

with open('./Puzzles.json', 'r') as f:
    puzzle_json = json.load(f)

with open('./puzzle_database.py', "w") as w:
    w.write("from typing import Dict\n\n"
        + "# Auto-generated by convert_json.py\n"
        + "PUZZLE_DATABASE: Dict = {\n"
        + "    \"vers\": \"" + puzzle_json["vers"] + "\",\n"
        + "    \"puzzles\": [\n")
    p = puzzle_json["puzzles"]
    puzzle_id = 1000
    for i in p:
        print(i)
        w.write("        {\n"
            + "            \"title\": \"" + i["title"] + "\",\n"
            + "            \"author\": \"" + i["author"] + "\",\n"
            + "            \"link\": \"" + i["link"] + "\",\n"
            + "            \"rating\": " + str(i["rating"]) + ",\n"
            #+ "            \"tags\": \"" + i["tags"] + "\",\n"
            + "            \"id\": " + str(puzzle_id) + ",\n"
            + "        },\n")
        puzzle_id += 10
    w.write("    ]\n}")